/// CcBorderParams: Design tokens for common border styles.
///
/// Provides semantic border configurations that can be reused across
/// the application to maintain visual consistency.
abstract class CcBorderParams {
  /// Subtle border for cards and containers.
  static const double subtleWidth = 1;

  /// Medium border for elevated components.
  static const double mediumWidth = 1.5;

  /// Strong border for focused or active states.
  static const double strongWidth = 2;
}
